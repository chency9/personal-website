import { readFile, mkdir, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const [component, checkbox, license] = await Promise.all([
  readFile(new URL('src/back-top-character.js', root), 'utf8'),
  readFile(new URL('public/vendor/rubber-hose/checkbox.js', root), 'utf8'),
  readFile(new URL('public/vendor/rubber-hose/LICENSE', root), 'utf8'),
]);

if (!/function\s+backTopComponent\s*\(\s*fx\s*\)/.test(component)) {
  throw new Error('src/back-top-character.js must define function backTopComponent(fx).');
}
if (/^\s*(?:import|export)\s/m.test(component)) {
  throw new Error('The back-to-top component must remain a classic script without imports or exports.');
}

const layers = {};
for (const name of ['box-0', 'box-1']) {
  const pattern = new RegExp(`^\\s*['"]${name}['"]:\\s*(['"])(data:image/webp;base64,[A-Za-z0-9+/=]+)\\1,?\\s*$`, 'm');
  const layer = pattern.exec(checkbox);
  if (!layer) throw new Error(`Missing painted layer ${name} in checkbox.js.`);
  layers[`backtop-${name}`] = layer[2];
}

const core = /^\/\/ >>> hose core[^\r\n]*\r?\n[\s\S]*?^\/\/ <<< hose core[^\r\n]*/m.exec(checkbox)?.[0];
if (!core) throw new Error('Missing complete hose core block in checkbox.js.');

const notice = license.trim().split(/\r?\n/).map(line => line ? ` * ${line}` : ' *').join('\n');
const script = `/*!
 * Back-to-top character. Generated by scripts/build-back-top.mjs.
 * Edit src/back-top-character.js; retain the upstream art and core license below.
 *
${notice}
 */
(() => {
${component.trim()}

// >>> art (copied from checkbox.js by scripts/build-back-top.mjs)
const ART = ${JSON.stringify(layers, null, 2)};
// <<< art

${core}

window.RubberHose.addArt(ART);
backTopComponent(window.RubberHose);
})();
`;

const directory = new URL('public/vendor/rubber-hose/', root);
const output = new URL('back-top.js', directory);
await mkdir(directory, { recursive: true });
await writeFile(output, script);
console.log(`Back-to-top component built: public/vendor/rubber-hose/back-top.js (${(Buffer.byteLength(script) / 1024).toFixed(1)} KiB).`);
